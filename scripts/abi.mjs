// Copies the contract ABIs from the Foundry build into app/src/lib/abi.js (run after `forge build`).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
const out = (file, name) => JSON.parse(readFileSync(new URL(`../contracts/out/${file}/${name}.json`, import.meta.url))).abi;
const abis = {
  fundAbi: out("Fund.sol", "Fund"),
  factoryAbi: out("FundryFactory.sol", "FundryFactory"),
  circuitsAbi: out("ITapeOut.sol", "ICircuits"),
  transistorsAbi: out("ITapeOut.sol", "ITransistors"),
};
mkdirSync(new URL("../app/src/lib/", import.meta.url), { recursive: true });
let js = "// Generated by scripts/abi.mjs from contracts/out. Do not edit.\n";
for (const [k, v] of Object.entries(abis)) js += `export const ${k} = ${JSON.stringify(v)};\n`;
js += `export const erc20Abi = ${JSON.stringify([
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ type: "address" }, { type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ type: "address" }, { type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
])};\n`;
writeFileSync(new URL("../app/src/lib/abi.js", import.meta.url), js);
console.log("wrote app/src/lib/abi.js");
